"use client";

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { ArrowLeft, ArrowRight, CheckCircle2, Code2, Copy, Crown, LayoutGrid, Lock, Sparkles, WandSparkles } from "lucide-react";
import { useAuth } from "@/components/auth-provider";
import PaymentModal from "@/components/PaymentModal";

type WizardStep = 0 | 1 | 2 | 3;

type PromptVariant = {
  title: string;
  prompt: string;
  locked?: boolean;
};

type BuildType = "Website" | "App";

const promptTierTitles = ["Basic", "Improved", "Optimized", "Pro", "Premium"] as const;

const buildTypes: BuildType[] = ["Website", "App"];

const websiteCategories = [
  "SaaS Dashboard",
  "Landing Page",
  "Marketing Website",
  "Portfolio",
  "E-commerce / Marketplace",
  "AI Product",
  "Internal Tool",
  "Content Platform",
];

const appCategories = [
  "Mobile App",
  "Cross-platform App",
  "Tablet App",
  "Desktop App",
  "PWA",
  "Internal App",
  "Customer App",
  "Admin App",
];

const websiteFrameworks = ["Next.js", "React + Vite", "Remix", "Astro", "SvelteKit", "Nuxt.js"];
const appFrameworks = ["React Native", "Expo", "Flutter", "Ionic", "Capacitor", "Tauri"];

const websiteStyles = ["Tailwind CSS", "Shadcn UI", "CSS Modules", "Styled Components", "Material UI", "Chakra UI", "Mantine"];
const appStyles = ["NativeWind", "React Native Paper", "Material 3", "Cupertino", "Ionic UI", "Tailwind CSS"];

const websiteBackends = ["FastAPI", "Node.js + Express", "NestJS", "Django", "Firebase Functions", "Supabase Edge Functions"];
const appBackends = ["FastAPI", "Node.js + Express", "NestJS", "Django", "Firebase Functions", "Supabase Edge Functions"];

const websiteDatabases = ["PostgreSQL", "MySQL", "MongoDB", "SQLite", "Supabase (Postgres managed)", "Firestore"];
const appDatabases = ["PostgreSQL", "MySQL", "MongoDB", "SQLite", "Supabase (Postgres managed)", "Firestore", "Realm"];

const stepLabels = ["Basic Info", "Configuration", "Review", "Generate Prompt"] as const;

export default function PromptProjectWizard() {
  const router = useRouter();
  const { plan, setPlan, setPlanTier, user, isAuthenticated } = useAuth();
  const [step, setStep] = useState<WizardStep>(0);
  const [projectType, setProjectType] = useState<BuildType>("Website");
  const [projectName, setProjectName] = useState("");
  const [description, setDescription] = useState("");
  const [primaryUserFlow, setPrimaryUserFlow] = useState("");
  const [category, setCategory] = useState(websiteCategories[0]);
  const [framework, setFramework] = useState(websiteFrameworks[0]);
  const [styleSystem, setStyleSystem] = useState(websiteStyles[0]);
  const [backend, setBackend] = useState(websiteBackends[0]);
  const [database, setDatabase] = useState(websiteDatabases[0]);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isGeneratingPrompt, setIsGeneratingPrompt] = useState(false);
  const [generatedPrompts, setGeneratedPrompts] = useState<PromptVariant[]>([]);
  const [selectedPromptIndex, setSelectedPromptIndex] = useState(0);
  const [copiedIndex, setCopiedIndex] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);
  const isGeneratingPromptRef = useRef(false);
  const lastAutoGeneratedKeyRef = useRef<string | null>(null);

  const generatedPrompt = generatedPrompts[selectedPromptIndex]?.prompt || "";
  const isPaidPlan = (plan || "free").toLowerCase() !== "free";
  const projectConfig = projectType === "App"
    ? {
        categories: appCategories,
        frameworks: appFrameworks,
        styles: appStyles,
        backends: appBackends,
        databases: appDatabases,
        label: "App",
      }
    : {
        categories: websiteCategories,
        frameworks: websiteFrameworks,
        styles: websiteStyles,
        backends: websiteBackends,
        databases: websiteDatabases,
        label: "Website",
      };
  const visiblePromptVariants =
    generatedPrompts.length > 0
      ? generatedPrompts
      : promptTierTitles.map((title, index) => ({
          title,
          prompt: isGeneratingPrompt ? "Generating prompt from the trained model..." : "Waiting for prompt generation.",
          locked: index >= 2,
        }));

  const summary = useMemo(
    () => [
      { label: "Project Name", value: projectName || "Untitled project" },
      { label: "Description", value: description || "No description added" },
      { label: "Primary User Flow", value: primaryUserFlow || "No user flow added" },
      { label: "Project Type", value: projectType },
      { label: "Category", value: category },
      { label: "Framework", value: framework },
      { label: "Style System", value: styleSystem },
      { label: "Backend", value: backend },
      { label: "Database", value: database },
    ],
    [projectName, description, primaryUserFlow, category, framework, styleSystem, backend, database],
  );

  const canContinueStep1 = projectName.trim().length > 0 && category.trim().length > 0;
  const canSubmit = canContinueStep1 && framework && styleSystem && backend && database;
  const generationKey = [projectType, projectName.trim(), description.trim(), primaryUserFlow.trim(), category, framework, styleSystem, backend, database].join("|");

  useEffect(() => {
    setCategory(projectConfig.categories[0]);
    setFramework(projectConfig.frameworks[0]);
    setStyleSystem(projectConfig.styles[0]);
    setBackend(projectConfig.backends[0]);
    setDatabase(projectConfig.databases[0]);
  }, [projectType]);

  const generatePrompt = useCallback(async () => {
    if (isGeneratingPromptRef.current) return;

    isGeneratingPromptRef.current = true;
    setIsGeneratingPrompt(true);
    setError(null);

    try {
      const controller = new AbortController();
      const timeoutId = window.setTimeout(() => controller.abort(), 30000);

      const response = await fetch("/api/ai/website-pro/generate-prompts", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "X-User-Plan": "paid",
        },
        signal: controller.signal,
        body: JSON.stringify({
          target: projectType,
          siteType: category,
          appType: projectType === "App" ? category : undefined,
          framework,
          styleSystem,
          backend,
          database,
          developerType: "full_stack",
          features: [projectName.trim(), category].filter(Boolean),
            userFlow: primaryUserFlow.trim() || description.trim() || "Define the key user journey before implementation.",
          projectStructure: "Modular and maintainable",
          testingRequirements: "Unit and integration coverage",
          uiComplexity: "Moderate",
          platformTarget: projectType,
          goal: `${projectName.trim()}\n\n${description.trim()}`.trim(),
          includeDiscoveryQuestions: false,
          useModelOutput: true,
        }),
      });

      window.clearTimeout(timeoutId);

      if (!response.ok) {
        throw new Error("Failed to generate prompt");
      }

      const data = (await response.json()) as { prompts?: PromptVariant[] };
      const prompts = Array.isArray(data.prompts) ? data.prompts : [];
      if (prompts.length === 0) {
        throw new Error("No prompt returned from the model");
      }

      // Normalize prompts: ensure each variant requests code-level scaffold/snippets
      const normalize = (p: PromptVariant, idx: number): PromptVariant => {
        const raw = (p.prompt || "").trim();
        const hasCodeCue = /\b(code|scaffold|file structure|pages\/|index\.|\.tsx|\.js|package.json|Dockerfile|app\/page)\b/i.test(raw);
        const metaPrompt = /write .*prompt/i.test(raw) || /more detailed prompt/i.test(raw) || /improved version/i.test(raw);
        const title = (p.title || promptTierTitles[idx] || "Variant").trim();

        // If server already returned code-style content, keep it. If it returned a meta request
        // (e.g., "Write a more detailed prompt..."), replace with a concrete scaffold tailored to the variant.
        if (!metaPrompt && hasCodeCue) return p;

        const goal = `${projectName.trim() || 'Project'}${description ? ' — ' + description.trim() : ''}`;

        const base = `Create a ${projectType} called ${projectName || 'my-app'} using ${framework} and ${styleSystem}. Backend: ${backend}. Database: ${database}. Goal: ${goal}.
Provide a complete starter scaffold and example code for the main app files, including folder structure, a sample ${framework} page (example: pages/index.tsx or app/page.tsx), a main layout, a basic API route (example: /api/hello), Tailwind configuration, and package.json scripts to run and build the app. Include runnable code snippets for the most important files and minimal instructions to run locally.`;

        let variantDetails = '';
        switch (title.toLowerCase()) {
          case 'improved':
            variantDetails = 'Make the code more explicit: include a simple project folder layout, example components for the main UI (Hero, CTA), form handling, and simple unit-test examples. Prefer readable, well-commented code.';
            break;
          case 'optimized':
            variantDetails = 'Add performance and SEO improvements: SSR/SSG choices, image optimization, route-based code-splitting, Lighthouse best-practices, and minimal profiling notes. Provide production-ready build scripts and caching suggestions.';
            break;
          case 'pro':
            variantDetails = 'Produce a production-ready scaffold: environment configuration, error handling, logging/observability hooks, CI/CD hints, Dockerfile example, and recommended deployment steps. Include security best-practices (CORS, helmet, input validation).';
            break;
          case 'premium':
            variantDetails = 'Provide advanced delivery: end-to-end testing strategy, deployment with a sample GitHub Actions workflow, monitoring and alerting suggestions, backup and scaling guidance, and optional paid integrations (analytics, error reporting).';
            break;
          default:
            variantDetails = 'Include helpful code examples and a runnable starter scaffold.';
        }

        const scaffold = `${base}\n\n${variantDetails}`;
        return { title: p.title, prompt: scaffold, locked: p.locked } as PromptVariant;
      };

      setGeneratedPrompts(prompts.map(normalize));
      setSelectedPromptIndex(0);
    } catch (submitError) {
      const message = submitError instanceof DOMException && submitError.name === "AbortError"
        ? "Prompt generation timed out. Try again."
        : submitError instanceof Error
          ? submitError.message
          : "Failed to generate prompt";
      setError(message);
    } finally {
      isGeneratingPromptRef.current = false;
      setIsGeneratingPrompt(false);
    }
  }, [backend, category, database, description, framework, primaryUserFlow, projectName, projectType, styleSystem]);

  useEffect(() => {
    if (step !== 3) return;
    if (generatedPrompts.length > 0 || isGeneratingPrompt) return;
    if (lastAutoGeneratedKeyRef.current === generationKey) return;

    lastAutoGeneratedKeyRef.current = generationKey;

    void generatePrompt();
  }, [step, generatedPrompts.length, generationKey, isGeneratingPrompt, generatePrompt]);

  const createProject = async () => {
    if (!canSubmit || isSubmitting) return;

    setIsSubmitting(true);
    setError(null);

    try {
      const response = await fetch("/api/website-pro/projects", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          target: projectType,
          siteType: category,
          framework,
          styleSystem,
          backend,
          database,
          goal: `${projectName.trim()}\n\n${description.trim()}`.trim(),
          generatedPrompt: generatedPrompt || undefined,
          generatedPrompts: generatedPrompts.length ? generatedPrompts : undefined,
          generatedPromptTitle: generatedPrompts[selectedPromptIndex]?.title,
        }),
      });

      if (!response.ok) {
        if (response.status === 403) {
          const txt = await response.text();
          throw new Error(txt || "You have reached your free student limit of 5 projects. Upgrade to continue creating more projects.");
        }
        throw new Error("Failed to create project");
      }

      const data = (await response.json()) as { project?: { id?: string } };
      const projectId = data.project?.id;

      if (projectId) {
        try {
          window.dispatchEvent(new CustomEvent("my-prompt:project-saved", { detail: { project: data.project } }));
        } catch {
          // ignore sync issues
        }

        router.push(`/projects/${projectId}`);
        return;
      }

      router.push("/projects");
    } catch (submitError) {
      setError(submitError instanceof Error ? submitError.message : "Failed to create project");
    } finally {
      setIsSubmitting(false);
    }
  };

  const [paymentOpen, setPaymentOpen] = useState(false);
  const [paymentPlan, setPaymentPlan] = useState<{ name: string; price: number; key: string } | null>(null);
  const [paymentLoading, setPaymentLoading] = useState(false);

  return (
    <div className="space-y-6">
      <section className="rounded-[28px] border border-[var(--app-border)] bg-[var(--app-surface)] p-5 shadow-sm">
        <div className="flex flex-col gap-3 md:flex-row md:items-start md:justify-between">
          <div>
            <p className="text-sm font-medium text-[var(--app-muted)]">Prompt Generator</p>
            <h1 className="mt-1 text-3xl font-semibold tracking-tight text-[var(--app-text)]">Create New Project</h1>
            <p className="mt-2 max-w-2xl text-sm text-[var(--app-muted)]">Set up your new prompt project in a few simple steps.</p>
          </div>

          <div className="rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-4 py-3 text-sm text-[var(--app-muted)]">
            <div className="flex items-center gap-2 font-medium text-[var(--app-text)]">
              <Sparkles size={16} className="text-[#4f46e5]" />
              Guided setup
            </div>
            <p className="mt-1 max-w-xs">Use the wizard to capture the prompt, stack, and delivery details in one place.</p>
          </div>
        </div>

        <div className="mt-6">
          <p className="text-sm font-medium text-[var(--app-text)]">What are you building?</p>
          <div className="mt-2 grid gap-3 sm:grid-cols-2">
            {buildTypes.map((item) => {
              const active = projectType === item;

              return (
                <button
                  key={item}
                  type="button"
                  onClick={() => setProjectType(item)}
                  className={`build-type-btn rounded-2xl border px-4 py-3 text-left transition ${active ? "border-[#4f46e5] active-build-type shadow-sm" : "border-[var(--app-border)] bg-[var(--app-surface-2)] hover:border-[#4f46e5]"}`}
                >
                  <p className="text-base font-semibold text-[var(--app-text)]">{item}</p>
                  <p className="mt-1 text-sm text-[var(--app-muted)]">
                    {item === "App"
                      ? "Mobile, desktop, or cross-platform builds with app-focused stacks."
                      : "Marketing sites, dashboards, and web platforms with website-focused stacks."}
                  </p>
                </button>
              );
            })}
          </div>
          <p className="mt-2 text-xs text-[var(--app-muted)]">The category and stack options below change with this selection.</p>
        </div>

        <div className="mt-6 grid gap-3 sm:grid-cols-3">
          {stepLabels.map((label, index) => {
            const active = step === index;
            const completed = step > index;

            return (
              <div key={label} className="flex items-center gap-3">
                <div
                  className={`flex h-10 w-10 items-center justify-center rounded-full border text-sm font-semibold ${
                    active
                      ? "border-[#4f46e5] bg-[#4f46e5] text-white"
                      : completed
                        ? "border-emerald-500 bg-emerald-500 text-white"
                        : "border-[var(--app-border)] bg-[var(--app-surface-2)] text-[var(--app-muted)]"
                  }`}
                >
                  {completed ? <CheckCircle2 size={16} /> : index + 1}
                </div>
                <div className="min-w-0">
                  <p className="text-sm font-medium text-[var(--app-text)]">{label}</p>
                  <div className="mt-2 h-1.5 rounded-full bg-[var(--app-surface-2)]">
                    <div
                      className={`h-1.5 rounded-full transition-all ${active || completed ? "bg-[#4f46e5]" : "bg-transparent"}`}
                      style={{ width: active || completed ? "100%" : "0%" }}
                    />
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      </section>

      <section className="rounded-[28px] border border-[var(--app-border)] bg-[var(--app-surface)] p-5 shadow-sm">
        {step === 0 ? (
          <div className="grid gap-5 lg:grid-cols-[1.2fr_0.8fr]">
            <div className="space-y-4">
              <div>
                <label className="text-sm font-medium text-[var(--app-text)]">Project Name *</label>
                <input
                  value={projectName}
                  onChange={(event) => setProjectName(event.target.value)}
                  className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-4 py-3 text-sm text-[var(--app-text)] outline-none transition focus:border-[#4f46e5]"
                  placeholder="e.g., Content Marketing Prompts"
                />
              </div>

              <div>
                <label className="text-sm font-medium text-[var(--app-text)]">Description</label>
                <textarea
                  value={description}
                  onChange={(event) => setDescription(event.target.value)}
                  className="mt-2 min-h-36 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-4 py-3 text-sm text-[var(--app-text)] outline-none transition focus:border-[#4f46e5]"
                  placeholder="Describe what this project is for..."
                />
              </div>
            </div>

            <div className="space-y-4 rounded-3xl border border-[var(--app-border)] bg-[var(--app-surface-2)] p-4">
              <div>
                <label className="text-sm font-medium text-[var(--app-text)]">{projectType} Category *</label>
                <select
                  value={category}
                  onChange={(event) => setCategory(event.target.value)}
                  className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-sm text-[var(--app-text)] outline-none transition focus:border-[#4f46e5]"
                >
                  {projectConfig.categories.map((item) => (
                    <option key={item} value={item}>
                      {item}
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="text-sm font-medium text-[var(--app-text)]">Primary User Flow</label>
                <textarea
                  value={primaryUserFlow}
                  onChange={(event) => setPrimaryUserFlow(event.target.value)}
                  className="mt-2 min-h-36 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-sm text-[var(--app-text)] outline-none transition focus:border-[#4f46e5]"
                  placeholder="e.g., Visitor signs up, completes onboarding, creates their first project, and returns to review progress."
                />
                <p className="mt-2 text-xs text-[var(--app-muted)]">This helps the prompt model focus on the actual journey the product should support.</p>
              </div>
            </div>
          </div>
        ) : null}

        <PaymentModal
          open={paymentOpen}
          onClose={() => setPaymentOpen(false)}
          onPay={(details) => {
            setPaymentOpen(false);
            try {
              if (paymentPlan) {
                setPlan('paid');
                setPlanTier(paymentPlan.key === 'elite' ? 'elite' : 'pro');
              }
            } catch {}
          }}
          plan={paymentPlan ?? { name: 'Pro', price: 16864, key: 'pro' }}
          loading={paymentLoading}
          loggedIn={Boolean(isAuthenticated)}
          userEmail={user?.email}
        />

        {step === 1 ? (
          <div className="grid gap-5 lg:grid-cols-2">
            <div className="rounded-3xl border border-[var(--app-border)] bg-[var(--app-surface-2)] p-4">
              <div className="flex items-center gap-2 text-sm font-semibold text-[var(--app-text)]">
                <LayoutGrid size={16} className="text-[#4f46e5]" />
                Project stack
              </div>
              <div className="mt-4 space-y-4">
                <label className="block text-sm">
                  <span className="font-medium text-[var(--app-text)]">Framework</span>
                  <select
                    value={framework}
                    onChange={(event) => setFramework(event.target.value)}
                    className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-[var(--app-text)] outline-none focus:border-[#4f46e5]"
                  >
                    {projectConfig.frameworks.map((item) => (
                      <option key={item} value={item}>{item}</option>
                    ))}
                  </select>
                </label>

                <label className="block text-sm">
                  <span className="font-medium text-[var(--app-text)]">Style System</span>
                  <select
                    value={styleSystem}
                    onChange={(event) => setStyleSystem(event.target.value)}
                    className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-[var(--app-text)] outline-none focus:border-[#4f46e5]"
                  >
                    {projectConfig.styles.map((item) => (
                      <option key={item} value={item}>{item}</option>
                    ))}
                  </select>
                </label>
              </div>
            </div>

            <div className="rounded-3xl border border-[var(--app-border)] bg-[var(--app-surface-2)] p-4">
              <div className="flex items-center gap-2 text-sm font-semibold text-[var(--app-text)]">
                <WandSparkles size={16} className="text-[#4f46e5]" />
                Runtime settings
              </div>
              <div className="mt-4 space-y-4">
                <label className="block text-sm">
                  <span className="font-medium text-[var(--app-text)]">Backend</span>
                  <select
                    value={backend}
                    onChange={(event) => setBackend(event.target.value)}
                    className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-[var(--app-text)] outline-none focus:border-[#4f46e5]"
                  >
                    {projectConfig.backends.map((item) => (
                      <option key={item} value={item}>{item}</option>
                    ))}
                  </select>
                </label>

                <label className="block text-sm">
                  <span className="font-medium text-[var(--app-text)]">Database</span>
                  <select
                    value={database}
                    onChange={(event) => setDatabase(event.target.value)}
                    className="mt-2 w-full rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-[var(--app-text)] outline-none focus:border-[#4f46e5]"
                  >
                    {projectConfig.databases.map((item) => (
                      <option key={item} value={item}>{item}</option>
                    ))}
                  </select>
                </label>
              </div>
            </div>
          </div>
        ) : null}

        {step === 2 ? (
          <div className="grid gap-4 lg:grid-cols-[1fr_0.9fr]">
            <div className="rounded-3xl border border-[var(--app-border)] bg-[var(--app-surface-2)] p-4">
              <div className="flex items-center gap-2 text-sm font-semibold text-[var(--app-text)]">
                <CheckCircle2 size={16} className="text-emerald-500" />
                Review project details
              </div>
              <div className="mt-4 rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] p-4 text-sm text-[var(--app-muted)]">
                <p className="font-medium text-[var(--app-text)]">Project summary</p>
                <p className="mt-2">{projectName || "Untitled project"}</p>
                <p>{primaryUserFlow || "No user flow added"}</p>
                <p>{category}</p>
                <p>{framework} · {styleSystem}</p>
                <p>{backend} · {database}</p>
              </div>
            </div>

            <div className="rounded-3xl border border-[var(--app-border)] bg-[linear-gradient(180deg,rgba(79,70,229,0.08),rgba(79,70,229,0.03))] p-4">
              <p className="text-sm font-semibold text-[var(--app-text)]">What happens next</p>
              <p className="mt-2 text-sm text-[var(--app-muted)]">Continue to generate prompts, review the cards, and then save the selected trained-model prompt with your project.</p>
            </div>
          </div>
        ) : null}

        {step === 3 ? (
          <div className="space-y-4">
            <div className="rounded-3xl border border-[var(--app-border)] bg-[var(--app-surface-2)] p-4">
              <div className="flex items-center gap-2 text-sm font-semibold text-[var(--app-text)]">
                <Code2 size={16} className="text-[#4f46e5]" />
                Trained model prompt
              </div>

              {isGeneratingPrompt ? (
                <div className="mt-4 rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface)] px-4 py-3 text-sm text-[var(--app-muted)]">Generating prompt from the trained model...</div>
              ) : null}

              <div className="mt-4">
                <p className="text-sm font-semibold text-[var(--app-text)]">Prompt cards</p>

                <div className="mt-3 grid grid-cols-2 gap-3">
                  {visiblePromptVariants.slice(0, 2).map((prompt, idx) => {
                    const index = idx;
                    const isLocked = !!prompt.locked && !isPaidPlan;
                    const active = selectedPromptIndex === index;
                    const cardTone = isLocked
                      ? "border-amber-200 bg-amber-50/70"
                      : active
                        ? "border-[#4f46e5] bg-[var(--active-card-bg)] shadow-sm"
                        : "border-[var(--app-border)] bg-[var(--app-surface)]";

                    return (
                      <div
                        key={prompt.title}
                        role="button"
                        tabIndex={0}
                        onClick={() => {
                          if (isLocked) return;
                          setSelectedPromptIndex(index);
                        }}
                        onKeyDown={(e) => {
                          if (e.key === 'Enter' || e.key === ' ') {
                            e.preventDefault();
                            if (isLocked) return;
                            setSelectedPromptIndex(index);
                          }
                        }}
                        className={`relative flex h-[250px] w-full flex-col overflow-hidden rounded-2xl border p-4 text-left transition ${cardTone} ${isLocked ? "opacity-80" : "hover:border-[#4f46e5]"}`}
                      >
                        <div className="flex items-start justify-between gap-3">
                          <p className="font-semibold text-[var(--app-text)]">{prompt.title}</p>
                          {!isLocked ? (
                            <span
                              role="button"
                              tabIndex={0}
                              onClick={(e) => {
                                e.stopPropagation();
                                navigator.clipboard.writeText(prompt.prompt || "");
                                setCopiedIndex(index);
                                window.setTimeout(() => setCopiedIndex(null), 2000);
                              }}
                              onKeyDown={(e) => {
                                if (e.key === 'Enter' || e.key === ' ') {
                                  e.preventDefault();
                                  (e as unknown as KeyboardEvent).stopPropagation();
                                  navigator.clipboard.writeText(prompt.prompt || "");
                                  setCopiedIndex(index);
                                  window.setTimeout(() => setCopiedIndex(null), 2000);
                                }
                              }}
                              className="inline-flex items-center gap-2 rounded-md bg-[var(--app-surface-2)] px-2 py-1 text-xs text-[var(--app-text)]"
                            >
                              <Copy size={14} /> Copy
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-1 rounded-full border border-amber-200 bg-amber-50 px-2.5 py-1 text-[10px] text-amber-700">
                              <Lock size={10} /> Premium
                            </span>
                          )}
                        </div>

                        <p className={`mt-2 overflow-hidden text-sm text-[var(--app-muted)] ${isLocked ? "line-clamp-3" : "line-clamp-6"}`}>{prompt.prompt}</p>

                        {copiedIndex === index ? <span className="mt-3 text-xs text-emerald-700">Copied!</span> : null}
                        {isLocked ? <p className="mt-2 text-xs font-medium text-amber-700">It is improved version. Upgrade to see the prompt.</p> : null}
                      </div>
                    );
                  })}
                </div>

                <div className="mt-3 grid grid-cols-3 gap-3">
                  {visiblePromptVariants.slice(2, 5).map((prompt, idx) => {
                    const index = idx + 2;
                    const isLocked = !!prompt.locked && !isPaidPlan;
                    const active = selectedPromptIndex === index;
                    const cardTone = isLocked
                      ? "border-amber-200 bg-amber-50/70"
                      : active
                        ? "border-[#4f46e5] bg-[var(--active-card-bg)] shadow-sm"
                        : "border-[var(--app-border)] bg-[var(--app-surface)]";

                    return (
                      <div
                        key={prompt.title}
                        role="button"
                        tabIndex={0}
                        onClick={() => {
                          if (isLocked) return;
                          setSelectedPromptIndex(index);
                        }}
                        onKeyDown={(e) => {
                          if (e.key === 'Enter' || e.key === ' ') {
                            e.preventDefault();
                            if (isLocked) return;
                            setSelectedPromptIndex(index);
                          }
                        }}
                        className={`relative flex h-[250px] w-full flex-col overflow-hidden rounded-2xl border p-4 text-left transition ${cardTone} ${isLocked ? "opacity-80" : "hover:border-[#4f46e5]"}`}
                      >
                        <div className="flex items-start justify-between gap-3">
                          <p className="font-semibold text-[var(--app-text)]">{prompt.title}</p>
                          {!isLocked ? (
                            <span
                              role="button"
                              tabIndex={0}
                              onClick={(e) => {
                                e.stopPropagation();
                                navigator.clipboard.writeText(prompt.prompt || "");
                                setCopiedIndex(index);
                                window.setTimeout(() => setCopiedIndex(null), 2000);
                              }}
                              onKeyDown={(e) => {
                                if (e.key === 'Enter' || e.key === ' ') {
                                  e.preventDefault();
                                  (e as unknown as KeyboardEvent).stopPropagation();
                                  navigator.clipboard.writeText(prompt.prompt || "");
                                  setCopiedIndex(index);
                                  window.setTimeout(() => setCopiedIndex(null), 2000);
                                }
                              }}
                              className="inline-flex items-center gap-2 rounded-md bg-[var(--app-surface-2)] px-2 py-1 text-xs text-[var(--app-text)]"
                            >
                              <Copy size={14} /> Copy
                            </span>
                          ) : (
                            <span className="inline-flex items-center gap-1 rounded-full border border-amber-200 bg-amber-50 px-2.5 py-1 text-[10px] text-amber-700">
                              <Lock size={10} /> Premium
                            </span>
                          )}
                        </div>

                        <p className={`mt-2 overflow-hidden text-sm text-[var(--app-muted)] ${isLocked ? "line-clamp-3" : "line-clamp-6"}`}>{prompt.prompt}</p>

                        {copiedIndex === index ? <span className="mt-3 text-xs text-emerald-700">Copied!</span> : null}
                        {isLocked ? <p className="mt-2 text-xs font-medium text-amber-700">It is improved version. Upgrade to see the prompt.</p> : null}
                      </div>
                    );
                  })}
                </div>
              </div>
            </div>
            <div className="mt-6 rounded-[20px] border border-[var(--app-border)] bg-[var(--app-surface)] p-4">
              <div className="flex items-start justify-between gap-4">
                <div>
                  <p className="text-sm font-semibold text-[var(--app-text)]">Generated Prompt</p>
                  <p className="mt-1 text-xs uppercase text-[var(--app-muted)]">{visiblePromptVariants[selectedPromptIndex]?.title || "Basic"}</p>
                </div>

                <div className="flex items-center gap-3">
                  <label className="text-sm text-[var(--app-muted)] flex items-center gap-2">
                    <span className="hidden sm:inline">Variant</span>
                    <select
                      value={selectedPromptIndex}
                      onChange={(e) => setSelectedPromptIndex(Number(e.target.value))}
                      className="rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-3 py-1 text-sm text-[var(--app-text)]"
                    >
                      {visiblePromptVariants.map((v, i) => (
                        <option key={v.title} value={i}>
                          {v.title}
                        </option>
                      ))}
                    </select>
                  </label>

                  <button
                    type="button"
                    onClick={() => {
                      const txt = generatedPrompt || visiblePromptVariants[selectedPromptIndex]?.prompt || "";
                      navigator.clipboard.writeText(txt);
                      setCopiedIndex(selectedPromptIndex);
                      window.setTimeout(() => setCopiedIndex(null), 2000);
                    }}
                    className="rounded-2xl bg-[#4f46e5] px-3 py-1 text-sm font-medium text-white"
                  >
                    Copy
                  </button>
                  {copiedIndex === selectedPromptIndex ? <span className="text-sm text-emerald-700">Copied!</span> : null}
                </div>
              </div>

              <div className="mt-4">
                <pre className="whitespace-pre-wrap rounded-[16px] border p-6 text-sm leading-7" style={{borderColor: 'var(--generated-prompt-border)', background: 'var(--generated-prompt-bg)', color: 'var(--generated-prompt-text)'}}>
                  {generatedPrompt || visiblePromptVariants[selectedPromptIndex]?.prompt}
                </pre>
              </div>

              <div className="mt-4">
                <p className="text-sm font-medium text-[var(--app-text)]">Other variants</p>
                <div className="mt-2 flex flex-wrap gap-3">
                  {visiblePromptVariants.slice(2, 5).map((v, i) => {
                    const index = i + 2;
                    const isLocked = !!v.locked && !isPaidPlan;
                    return (
                      <button
                        key={v.title}
                        type="button"
                        onClick={() => {
                          if (isLocked) {
                            // open payment modal with plan mapping
                            const mapping: Record<string, { name: string; price: number; key: string }> = {
                              Optimized: { name: 'Pro', price: 16864, key: 'pro' },
                              Pro: { name: 'Pro', price: 16864, key: 'pro' },
                              Premium: { name: 'Elite', price: 1999, key: 'elite' },
                            };
                            const plan = mapping[v.title] ?? { name: 'Pro', price: 16864, key: 'pro' };
                            setPaymentPlan(plan);
                            setPaymentOpen(true);
                            return;
                          }
                          setSelectedPromptIndex(index);
                        }}
                        className={`rounded-2xl border px-3 py-2 text-sm font-medium ${selectedPromptIndex === index ? 'variant-selected' : 'border-[var(--app-border)] bg-[var(--app-surface-2)]'}`}
                      >
                        <div className="flex items-center gap-2">
                          <span>{v.title}</span>
                        </div>
                      </button>
                    );
                  })}
                </div>
              </div>
            </div>
          </div>
        ) : null}

        {error ? <p className="mt-4 rounded-2xl border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">{error}</p> : null}

        <div className="mt-6 flex flex-wrap items-center justify-between gap-3 border-t border-[var(--app-border)] pt-4">
          <button
            type="button"
            onClick={() => setStep((current) => Math.max(0, current - 1) as WizardStep)}
            disabled={step === 0}
            className="inline-flex items-center gap-2 rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-4 py-2.5 text-sm font-medium text-[var(--app-text)] disabled:cursor-not-allowed disabled:opacity-50"
          >
            <ArrowLeft size={14} />
            Back
          </button>

          <div className="flex flex-wrap gap-3">
            <button
              type="button"
              onClick={() => router.push("/dashboard")}
              className="rounded-2xl border border-[var(--app-border)] bg-[var(--app-surface-2)] px-4 py-2.5 text-sm font-medium text-[var(--app-text)]"
            >
              Cancel
            </button>

            {step < 3 ? (
              <button
                type="button"
                onClick={() => setStep((current) => Math.min(3, current + 1) as WizardStep)}
                disabled={step === 0 ? !canContinueStep1 : false}
                className="inline-flex items-center gap-2 rounded-2xl bg-[#4f46e5] px-4 py-2.5 text-sm font-semibold text-white disabled:cursor-not-allowed disabled:opacity-50"
              >
                Continue
                <ArrowRight size={14} />
              </button>
            ) : (
              <button
                type="button"
                onClick={() => void createProject()}
                disabled={!canSubmit || isSubmitting}
                className="inline-flex items-center gap-2 rounded-2xl bg-[#4f46e5] px-4 py-2.5 text-sm font-semibold text-white disabled:cursor-not-allowed disabled:opacity-50"
              >
                {isSubmitting ? "Creating..." : "Create Project"}
                <ArrowRight size={14} />
              </button>
            )}
          </div>
        </div>
      </section>
    </div>
  );
}